const FALLBACK = ['#C9BFAE', '#E4DED2']

/** Colores de la bandera del país, o un par neutro si no lo conocemos. */
export function flagColors(countryCode: string | null | undefined): string[] {
  return (countryCode && FLAG_COLORS[countryCode.toLowerCase()]) || FALLBACK
}

/** El cuadrado de la bandera: sus colores en franjas inclinadas (como el diseño de Italia). */
export function flagStripesGradient(countryCode: string | null | undefined): string {
  const colors = flagColors(countryCode)
  const step = 100 / colors.length
  return `linear-gradient(106deg, ${colors.map((color, index) => `${color} ${(index * step).toFixed(1)}% ${((index + 1) * step).toFixed(1)}%`).join(', ')})`
}

/** Los tres puntitos de la tarjeta: los colores de la bandera, repetidos si tiene menos de tres. El blanco,
    algo más oscuro para que se vea sobre la tarjeta. */
export function flagDots(countryCode: string | null | undefined): string[] {
  const colors = flagColors(countryCode)
  return [0, 1, 2].map((index) => {
    const color = colors[index % colors.length]
    return color === W ? '#E4DED2' : color
  })
}

/** "it" → "Italia", con el nombre del país en español que ya sabe el navegador. */
export function countryNameEs(countryCode: string | null | undefined): string {
  if (!countryCode) return 'Destino'
  try {
    return new Intl.DisplayNames(['es'], { type: 'region' }).of(countryCode.toUpperCase()) ?? countryCode.toUpperCase()
  } catch {
    return countryCode.toUpperCase()
  }
}
