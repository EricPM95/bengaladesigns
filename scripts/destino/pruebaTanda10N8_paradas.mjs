import fs from 'node:fs'
import { conViaje, modulo, esp, preparar, foto } from './_10n6_k3_comun.mjs'
const { debe, fin } = preparar()
const L = (f) => fs.readFileSync(f, 'utf8')
const sinCom = (s) => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')
console.log('1. Código')
{
  const hd = L('src/components/ui/HojaDia.tsx')
  debe(['#FBF3E2', '#1C2230', '#E9C77A', 'linear-gradient(135deg,#F3E2B0,#D2B67A 55%,#B58A2E)', 'Instrument Serif'].every((t) => hd.includes(t)), 'ap3i', 'HojaDia con los colores y la letra de Piezas/Hoja Dia')
  for (const f of ['route/freeDay/AddToDaySheet', 'route/reservas/FreeTourDiaSheet', 'route/dayDetail/MoverADia', 'route/excursions/ExcursionSinHueco', 'route/excursions/WhereSheet', 'propuesta/HojaRecomendacion', 'route/reservas/VolverExcursionARuta', 'route/dayDetail/DayPositionPicker'])
    debe(/HojaDia/.test(L(`src/components/${f}.tsx`)), 'ap3i', `${f} usa HojaDia`)
  debe(!/entradas con hora/.test(sinCom(L('src/components/route/freeDay/AddToDaySheet.tsx'))), 'ap3g', 'al añadir un sitio no se bloquea ningún día por entradas con hora')
  const ft = sinCom(L('src/lib/freeTourEnDia.ts'))
  debe(!/rebuild-day|replaceDayRebuilt|force_order/.test(ft), 'ap3', 'el Free Tour no rehace días con el motor')
  const q = sinCom(L('src/components/route/dayDetail/QuitarConEntradaDialog.tsx'))
  debe(/Quitar parada/.test(q) && /Quitar también la entrada/.test(q) && !/>\s*Cancelar\s*</.test(q) && !/La entrada se queda/.test(q), 'ap8ba', 'confirmación con dos botones, sin [Cancelar] ni la línea de RESERVAS')
  debe(!/\{cancelLabel\}/.test(L('src/components/route/ConfirmDialog.tsx')), 'ap8b', 'las confirmaciones no pintan [Cancelar]')
  debe(!/Su hora la fija/.test(L('src/components/route/dayDetail/StopMenu.tsx')), 'ap8bb', 'Mover antes/después sin aviso de horas')
  const cp = L('src/components/route/dayDetail/CambiarParada.tsx')
  debe(!/initialFilters/.test(cp) && /Cambiar \$\{displayStopName/.test(cp), 'ap8bc', 'Cambiar parada sin filtros y con título «Cambiar X»')
  debe(!/data-pregunta-cambiar-parada/.test(L('src/components/route/placeExplorer/PlaceExplorerScreen.tsx')), 'ap8bc', 'sin la franja de pregunta')
  const pr = L('src/lib/propuesta.ts')
  debe(/Pasar el Free Tour/.test(pr) && /Cambiar el orden de los días/.test(pr) && /a la excursión/.test(pr), 'ap3h', 'propuesta: una frase por cambio')
  const rs = fs.readdirSync('src/components/route/reservas').map((x) => L(`src/components/route/reservas/${x}`)).join('\n')
  debe(!/Quitar el Free Tour/i.test(sinCom(rs)), 'ap3j', 'sin «Quitar el Free Tour»')
}
console.log('2. En la app')
const a = await conViaje({ version: 'gratis', alto: 844 })
try {
  const ev = (js) => a.evaluar(js)
  const st = (js) => ev(modulo('/src/store/useRouteStore.ts') + `.then((m) => { const s = m.useRouteStore.getState(); const r = s.route; ${js} })`)
  for (let i = 0; i < 40 && !(await st('return r.days.some((d)=>d.stops.length>5)')); i++) await esp(500)
  const firmas = () => st("return r.days.map((d) => d.curatedId + ':' + d.stops.map((x) => x.id).join(','))")
  const antes = await firmas()
  const dias = await st('return r.days.filter((d)=>!d.isReturnLeg).map((d)=>d.id)')
  const rf = await ev(modulo('/src/lib/freeTourEnDia.ts') + `.then((m) => m.anadirFreeTourEnDia(${JSON.stringify(dias[1])}))`)
  debe(rf.ok, 'ap3a', `añadir el Free Tour: ${JSON.stringify(rf)}`)
  const info = await st('const d = r.days.find((x)=>x.stops.some((y)=>y.isFreeTour)); return { n: d.dayNumber, i: d.stops.findIndex((y)=>y.isFreeTour), fr: d.stops[0].franja }')
  debe(info.n === 2 && info.i === 0 && info.fr === 'manana', 'ap3a', `de primera parada por la mañana (${JSON.stringify(info)})`)
  const desp = await firmas()
  debe(desp.filter((x, i) => x !== antes[i]).length === 1, 'ap3a', 'solo cambia el día elegido; ningún otro día se mueve')
  const otra = await ev(modulo('/src/lib/freeTourEnDia.ts') + `.then((m) => m.anadirFreeTourEnDia(${JSON.stringify(dias[0])}))`)
  debe(!otra.ok, 'ap3c', 'una sola vez en la ruta')
  const abrirMenuDe = (txt) => ev(`(() => { const b = Array.from(document.querySelectorAll('[data-menu-hoja="parada"]')).find((x) => { let e = x; for (let i = 0; i < 6 && e.parentElement; i++) e = e.parentElement; return e.textContent.includes(${JSON.stringify(txt)}) }); if (!b) return false; b.scrollIntoView({block:'center'}); b.click(); return true })()`)
  await st("s.setMode('days'); s.setActiveDayId(r.days[1].id); return true")
  await esp(2000)
  debe(await abrirMenuDe('Free Tour'), 'ap3b', 'el «···» del Free Tour')
  await esp(800)
  await ev("Array.from(document.querySelectorAll('[data-opcion-hoja]')).find((t) => t.textContent.includes('Mover a otro día'))?.click(); true")
  await esp(800)
  const hoja = await ev("(() => { const h = document.querySelector('[data-hoja-dia]'); if (!h) return null; return { t: h.querySelector('[data-hoja-dia-titulo]').textContent, filas: Array.from(h.querySelectorAll('[data-dia-id]')).map((b) => ({ b: b.hasAttribute('data-bloqueado'), x: b.textContent })), btn: h.querySelector('[data-hoja-dia-boton]').textContent } })()")
  debe(hoja && hoja.t === '¿A qué día lo pasamos?' && hoja.filas.filter((f) => f.b).length === 1 && /ya está en ese día/.test(hoja.filas.find((f) => f.b).x) && /^Pasar al /.test(hoja.btn), 'ap3i', `Hoja Dia 01: ${JSON.stringify(hoja)}`)
  await a.captura(foto('n8_hoja_dia_mover'))
  await ev("document.querySelector('[data-hoja-dia-boton]').click(); true")
  await esp(1500)
  const m2 = await st('const d = r.days.find((x)=>x.stops.some((y)=>y.isFreeTour)); return { n: d.dayNumber, i: d.stops.findIndex((y)=>y.isFreeTour), fr: d.stops[0].franja }')
  debe(m2.n !== 2 && m2.i === 0 && m2.fr === 'manana', 'ap3b', `pasa de primero al otro día (${JSON.stringify(m2)})`)
  await esp(2500)
  debe(await abrirMenuDe('Free Tour'), 'ap3d', 'el «···» otra vez')
  await esp(800)
  await ev("document.querySelector('[data-hoja-opciones] [data-peligro]')?.click(); true")
  await esp(900)
  debe((await st('return r.days.some((d)=>d.stops.some((y)=>y.isFreeTour))')) === false, 'ap3d', 'Quitar parada lo quita de verdad y al momento')
  debe((await st("return (r.answers.experiencesPositive ?? []).includes('free_tour')")) === false, 'ap3d', 'y la ruta deja de pedirlo')
  await ev(modulo('/src/store/useAddFlowStore.ts') + '.then((m) => m.useAddFlowStore.getState().undo())')
  await esp(600)
  debe(await st('return r.days.some((d)=>d.stops.some((y)=>y.isFreeTour))'), 'ap3d', '[Deshacer] lo devuelve')
  const nombre = await st('return r.days[0].stops[1].name')
  await st(`s.addReservation({ id: 'res-n8', kind: 'entrada', refId: ${JSON.stringify(nombre)}, name: ${JSON.stringify(nombre)}, placeNames: [${JSON.stringify(nombre)}], dateIso: null, dayNumber: 1, time: '09:15' }); s.setActiveDayId(r.days[0].id); return true`)
  await esp(2000)
  await abrirMenuDe(nombre)
  await esp(900)
  const op = await ev("Array.from(document.querySelectorAll('[data-opcion-hoja]')).map((t) => ({ x: t.textContent, d: t.hasAttribute('data-deshabilitada') }))")
  const g = (n) => op.find((o) => o.x.includes(n))
  debe(g('Mover antes') && !g('Mover antes').d && g('Mover después') && !g('Mover después').d && !/Su hora/.test(g('Mover antes').x), 'ap8bb', 'Mover antes/después activos con entrada')
  debe(g('Mover a otro día')?.d && g('Cambiar parada')?.d, 'ap8bb', 'Mover a otro día y Cambiar parada siguen en gris')
  await ev("document.querySelector('[data-hoja-opciones] [data-peligro]')?.click(); true")
  await esp(900)
  const dlg = await ev("document.querySelector('[data-hoja=\"quitar-con-entrada\"]')?.textContent ?? null")
  debe(dlg && !/Cancelar/.test(dlg) && /Quitar parada/.test(dlg) && /Quitar también la entrada/.test(dlg), 'ap8ba', `confirmación: ${dlg}`)
  await a.captura(foto('n8_quitar_con_entrada'))
} finally {
  a.cerrar()
}
fin('pruebaTanda10N8_paradas')
